func init() {
	for _, line := range strings.Split(krnlnData, "\n") {
		line = strings.TrimSpace(line)
		if line == "" { continue }
		idx := strings.Index(line, ":")
		if idx < 0 { continue }
		off, err := strconv.Atoi(line[:idx])
		if err != nil { continue }
		name := line[idx+1:]
		krnlnByID[int32(off/4)] = name
	}
	libCmdTables["krnln"] = krnlnByID
}

// lookupLibCommand 按支持库内部名/中文名查命令名。找不到返回空串。
func lookupLibCommand(lib *LibraryRef, methodID int32) string {
	if lib == nil { return "" }
	var tbl map[int32]string
	// 先按内部文件名（去扩展名）匹配
	key := strings.ToLower(strings.TrimSuffix(lib.FileName, ".fnr"))
	key = strings.TrimSuffix(key, ".fne")
	if t, ok := libCmdTables[key]; ok { tbl = t }
	// 再按中文名匹配
	if tbl == nil {
		switch lib.Name {
		case "系统核心支持库": tbl = libCmdTables["krnln"]
		case "多线程支持库": tbl = libCmdTables["EThread"]
		case "特殊功能支持库": tbl = libCmdTables["spec"]
		case "数据操作支持库": tbl = libCmdTables["dp1"]
		case "互联网支持库": tbl = libCmdTables["internet"]
		case "操作系统界面功能支持库": tbl = libCmdTables["shell"]
		case "应用接口支持库": tbl = libCmdTables["eAPI"]
		}
	}
	if tbl == nil { return "" }
	return tbl[methodID]
}
